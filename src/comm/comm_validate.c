/*
 * comm_validate_record(p) = validate a received exchange record p (header 0x100 bytes; the only
 * callers are comm_exchange_initiator / comm_exchange_target on the records of F70b, never a bare item file).
 * Returns 0 = OK, 0x4D = invalid:
 *   1. bytes 0..5 == "TAMAGO" (D_25624D8);
 *   2. 0x100 <= total length (u32 at 0x48, a native little-endian read: exchange records
 *      store it little-endian, the item files big-endian, so a bare file fails here)
 *      <= 0xF000;
 *   3. the 16-bit additive checksum of all bytes but the last two (comm_record_sum) equals
 *      the u16 in the last two bytes, read LITTLE-endian (the two bytes are stored
 *      reversed on the stack and byte-swapped back by util_read_be16), as flash_fill
 *      writes it;
 *   4. the SIGNATURE at 0x52..0x59: K = p[0x55]; for i = 0..7, i != 3:
 *      p[0x52 + D_2562458[(K & 15) * 8 + i]] == D_25623D8[(K >> 4) * 8 + i]
 *      (D_2562458 = 16 permutations of 0..7 whose 4th byte is the row index, D_25623D8 =
 *      16 rows of expected values whose 4th byte is K & 0xF0; so byte 3 of the field is
 *      the key and the other 7 bytes are a table-driven function of it: 256 valid
 *      signatures exist. Every item file in the dump and all 916 files of the download
 *      pack carry a valid one, but this function, the only user of the two tables, is
 *      never applied to a file: the files' signatures are not checked by the firmware);
 *   5. bit 0 of p[0xFF] set ("record complete"; the item files have 0x10 there);
 *   6. record version / type u16 at 0x84 is 0, 1 or 3 (2 and > 3 rejected).
 * There is no cryptographic check anywhere: anyone who knows the two 128-byte tables can
 * forge a record.
 */
int comm_validate_record(struct TamagoFile *pp)
{
    u16 sum;
    u8 b[2];
    u8 pad[8];
    char tag[10];
    u8 *p = (u8 *)pp;
    u8 *e = p;
    int i;
    u16 v;

    memset(tag, 0, 10);
    strcpy(tag, D_25624D8);
    if (strncmp((char *)p, tag, 6) != 0)
        return 0x4d;
    if (*(u32 *)(p + 0x48) - 0x100 > 0xef00)
        return 0x4d;
    comm_record_sum(p, *(u32 *)(p + 0x48), &sum);
    e += *(u32 *)(p + 0x48) - 2;
    b[1] = *e++;
    b[0] = *e;
    v = util_read_be16((int)b);
    if (sum != v)
        return 0x4d;
    for (i = 0; i <= 7; i++) {
        if (i == 3)
            continue;
        if (((u8 *)(((const u8 *)D_2562458)[(p[0x55] & 15) * 8 + i] + (int)p))[0x52] != ((const u8 *)D_25623D8)[(p[0x55] >> 4) * 8 + i])
            return 0x4d;
    }
    if (!(p[0xff] & 1))
        return 0x4d;
    switch (*(u16 *)(p + 0x84)) {
    case 2:
        break;
    case 0:
    case 1:
    case 3:
        goto zero;
    }
    return 0x4d;
zero:
    return 0;
}

