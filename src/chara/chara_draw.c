extern const u8 *D_AF9C[][15] __asm__("chara_sprite_sets");
/*
 * Draw any character g (built-in id or downloaded) with pose c in objects a..a+2.
 */
void chara_draw_any(u8 a, u8 b, u8 c, u16 d, s16 x, s16 y, int g)
{
    u16 e = g;
    struct GfxObject *p;

    p = &gfx_objects[a];
    if (e <= 5000) {
        gfx_object_set_flags(a, d);
        gfx_object_set_image(a, b, 0, D_AF9C[chara_table[e].sprite_set][c]);
    } else {
        gfx_object_set_flags(a, d);
        gfx_object_set_image(a, b, 0, (const u8 *)dl_chara_pose_pic(e + 0x77, c));
    }
    x -= p->image[0] >> 1;
    y = y - (p->image[1] >> 1) + 0x1c;
    gfx_object_move_dirty(a, x, y);
    chara_draw_clothes(a, a + 1, c, d, x, y, 0, e);
    chara_draw_accessory(a, a + 2, c, d, x, y, 0, e);
}

/*
 * Next owned accessory slot of list A (D_2535F50, 21 entries) after i (0..20, wrapping),
 * skipping the worn one (pet.worn_accessory); 0 = "none" is valid unless it is the worn one.
 */
int item_next_owned_accessory(int i)
{
    while (1) {
        i++;
        if (i > 20) {
            i = 0;
            if (save.pet.worn_accessory == i)
                continue;
            break;
        }
        if (i == save.pet.worn_accessory)
            continue;
        if (item_get_count(D_2535F50[i]))
            break;
    }
    return i;
}

/*
 * The same as item_next_owned_accessory for the clothes (list B: D_2535F68, 11 entries, 0..10; worn
 * one pet.worn_clothes).
 */
int item_next_owned_clothes(int k)
{
    for (;;) {
        k++;
        if (k > 10) {
            k = 0;
            if (save.pet.worn_clothes == 0)
                continue;
            break;
        }
        if (k == save.pet.worn_clothes)
            continue;
        if (item_get_count(D_2535F68[k]))
            break;
    }
    return k;
}

