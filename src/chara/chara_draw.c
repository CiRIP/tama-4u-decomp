/*
 * The wardrobe menu "ようふく / アクセサリー" (table ui_wardrobe_menu_tbl: {label, handler, inventory
 * index}), which runs the two dress-up menus; an entry is greyed (and refused) when that
 * inventory is empty or the character is transformed (x000 != its base id,
 * pet_get_id). Returns the handler's result, 0 on C, -1 on timeout.
 */
int ui_wardrobe_menu(void)
{
    int r;
    u8 sel;
    int i;
    u8 n;

    r = 0;
    sel = 0;
again:
    ui_new_screen();
    gfx_object_create(0, 0x1c, 0, 0, 0, D_2104794);
    for (i = 0; i <= 1; i++) {
        if (ui_wardrobe_menu_tbl[i].label == 0)
            break;
        gfx_draw_text_line(!item_inv_owned_count(&item_inventories[ui_wardrobe_menu_tbl[i].inventory]) || save.pet.x000 != pet_get_id() ? gfx_object_create(0x18, 0x20, i * 4 + 0x30, 0, 3, 0) : gfx_object_create(0x18, 0x20, i * 4 + 0x30, 0, 0, 0), 0x18, i * 16 + 0x20, i * 4 + 0x30, ui_wardrobe_menu_tbl[i].label, 0, 8);
    }
    n = gfx_object_create(6, sel * 16 + 0x22, 0x20, 0, 0, D_2104714);
    func_00009A6();
    ui_timeout = 10;
    btn_a_presses = 0;
    btn_b_presses = 0;
    btn_c_presses = 0;
    for (;;) {
        if (btn_a_presses) {
            sel++;
            if (sel > 1)
                sel = 0;
            gfx_object_move_dirty(n, 6, sel * 16 + 0x22);
            func_00009A6();
            ui_timeout = 10;
            btn_a_presses = 0;
        }
        if (btn_b_presses) {
            if (!item_inv_owned_count(&item_inventories[ui_wardrobe_menu_tbl[sel].inventory]) || save.pet.x000 != pet_get_id()) {
                snd_error_beep();
                btn_b_presses = 0;
                ui_timeout = 10;
                continue;
            }
            btn_b_presses = 0;
            ui_timeout = 10;
            r = ((int (*)(void))ui_wardrobe_menu_tbl[sel].x004)();
            if (r == 0 && ui_timeout != 0) {
                btn_b_presses = r;
                ui_timeout = 10;
                goto again;
            }
            return r;
        }
        if (btn_c_presses) {
            ui_timeout = 10;
            break;
        }
        sys_idle_tick();
        if (ui_timeout == 0) {
            r = -1;
            break;
        }
    }
    return r;
}

