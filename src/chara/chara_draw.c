/*
 * Place the ACCESSORY sprite b (slot A, object id+2) on top of character sprite a (pose
 * c, flags d, position e/f, accessory slot g (0 = the character's own built-in one, table
 * x018 of character h), character id h): picks the image set (the worn accessory's item
 * record pictures from D_2535F50[g] via item_load_pictures into chara_accessory_pics, or the built-in
 * default outfit set D_226C8EC / a downloaded character's at +0x3C68) and the per-pose
 * anchor offset (tables D_2535F74 / D_2535FCC: x - 0x40, y - 0x32; pose 11 = hidden),
 * honouring the pose flags (0x10 h-flip, 0x20 v-flip, 0x40 swap x/y). In the away modes
 * the position is fixed.
 */
struct CharaEntryShifted {
    u8 pad[0x18];
    u16 own_accessory;
    u8 pad2[0x14];
};
/* row k of chara_table seen from its x002 field */
#define D_255B4DE ((const struct CharaEntryShifted *)&chara_table[0].id)
extern u32 D_226C8EC[];
extern u32 chara_accessory_pics[];
extern const u8 D_2535F74[];
extern const u8 D_2535F90[];
extern const u8 D_2535FCC[29][4][28];
void chara_draw_accessory(u8 a, u8 b, u8 c, u16 d, s16 e, s16 f, u8 g, u16 h)
{
    struct GfxObject *A;
    struct GfxObject *B;
    u8 *tbl;
    s16 x, y, tmp;
    int flag = 0;
    u8 k;
    struct TamagoFile *it;
    u8 *p;
    int n, i;
    struct DlCharaRecord *s;
    u16 m;
    u8 *q;
    struct CharaEntryShifted *tb;
    u8 t;

    t = gfx_palette_slot_for(b, 0, 0);
    A = &gfx_objects[a];
    B = &gfx_objects[b];
    k = chara_fit_class(h);
    tbl = D_2535F74;
    if (k == 0)
        goto zero;
    k = k - 1;
    it = (struct TamagoFile *)chara_special_accessory_stub();
    if ((int)it != -1)
        flag = 1;
    if (g != 0 || flag != 0) {
        if (flag == 0)
            it = item_record_by_index(D_2535F50[g]);
        if (it == 0)
            goto zero;
        if (it->x000 == -1)
            goto zero;
        item_load_pictures(chara_accessory_pics, it, 7);
        if (it->x04e == 0x81) {
            chara_accessory_offsets = (u32)((u8 *)it + k * 28 + 0x202);
        } else {
            tbl = D_2535F90;
            i = item_get_id(it) - 0xde;
            if (i > 9)
                i -= 4;
            chara_accessory_offsets = (u32)((const u8 *)D_2535FCC + (k * 28 + i * 112));
        }
    } else if (h <= 5000) {
        chara_accessory_offsets = chara_own_accessory_offsets[D_255B4DE[h].own_accessory];
        for (i = 0; i < 4; i++)
            chara_accessory_pics[i] = D_226C8EC[D_255B4DE[h].own_accessory * 4 + i];
    } else {
        s = dl_chara_record(h + 0x77);
        if (s->x018 != 0) {
            chara_accessory_offsets = (u32)s + 0x4568;
            s = (struct DlCharaRecord *)((u8 *)s + 0x3c68);
            for (i = 0; i < 4; i++) {
                chara_accessory_pics[i] = (u32)s;
                s = (struct DlCharaRecord *)((u8 *)s + 0x156);
            }
        } else {
            chara_accessory_offsets = 0;
            for (i = 0; i < 4; i++)
                chara_accessory_pics[i] = 0;
        }
    }
    goto draw;
zero:
    chara_accessory_offsets = 0;
    chara_accessory_pics[0] = 0;
draw:
    if (chara_accessory_offsets != 0) {
        if (c != 11) {
            if (c > 11)
                c--;
            x = ((u8 *)chara_accessory_offsets)[c * 2] - 0x40;
            if (d & 0x10)
                x = -x;
            y = ((u8 *)chara_accessory_offsets)[c * 2 + 1] - 0x32;
            if (d & 0x20)
                y = -y;
            if (d & 0x40) {
                tmp = x;
                x = y;
                y = tmp;
            }
            if (tbl[c * 2 + 1] & 0x40) {
                m = 0;
                if (d & 0x10)
                    m = 0x20;
                if (d & 0x20)
                    m |= 0x10;
                d &= 0xffcf;
                d |= m;
            }
            q = (u8 *)(c * 2 + (u32)tbl);
            gfx_object_set_flags(b, d ^ q[1]);
            gfx_object_set_image(b, t, 0, (const u8 *)chara_accessory_pics[q[0] - 1]);
        }
        if (room_view == 2 || room_view == 3)
            gfx_object_move_dirty(b, 0x17 - (B->image[0] >> 1), 0x5c - (B->image[1] >> 1));
        else
            gfx_object_move_dirty(b, e + x + (A->image[0] >> 1) - (B->image[0] >> 1),
                         f + y + (A->image[1] >> 1) - (B->image[1] >> 1));
    } else
        gfx_object_set_image(b, 0, 0, 0);
}

