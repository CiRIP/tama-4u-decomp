/*
 * The CLOTHES sprite (slot B, object id+1) of a character drawing: the same as
 * chara_draw_accessory with the clothes list D_2535F68, offset tables D_2535FAC / D_2536CD0 and
 * default outfit table 0x226CE9C (asm).
 */
void chara_draw_clothes(u8 a, u8 b, u8 c, u16 d, s16 e, s16 f, u8 g, u16 h)
{
    struct GfxObject *A;
    struct GfxObject *B;
    u8 t;
    s16 x, y, tmp;
    u8 k;
    struct TamagoFile *it;
    int i;
    struct DlCharaRecord *s;
    u32 p;
    u16 m;
    const u8 *q;
    u16 o;

    t = gfx_palette_slot_for(b, 0, 0);
    A = &gfx_objects[a];
    B = &gfx_objects[b];
    k = chara_fit_class(h);
    if (k == 0)
        goto zero;
    k = k - 1;
    if (g != 0) {
        it = item_record_by_index(D_2535F68[g]);
        item_load_pictures(chara_clothes_pics, it, 0x1c);
        for (i = 0; i <= 6; i++)
            chara_clothes_pics[i] = chara_clothes_pics[k * 7 + i];
    } else if (h <= 5000) {
        for (i = 0; i <= 6; i++)
            chara_clothes_pics[i] = chara_default_outfits[chara_table[h].default_outfit * 7 + i];
    } else {
        s = dl_chara_record(h + 0x77);
        if (s->x01a != 0) {
            p = (u32)s + 0x31d2;
            for (i = 0; i <= 6; i++) {
                chara_clothes_pics[i] = p;
                if (i <= 4)
                    p += 0x13a;
                else
                    p += 0x23a;
            }
        } else {
            for (i = 0; i <= 6; i++)
                chara_clothes_pics[i] = 0;
        }
    }
    if (D_2535FAC[c * 2] == 0)
        goto zero;
    k = k * 7 + D_2535FAC[c * 2] - 1;
    x = ((const u8 *)D_2536CD0)[k * 2] - 0x40;
    if (d & 0x10)
        x = -x;
    y = ((const u8 *)D_2536CD0)[k * 2 + 1] - 0x32;
    if (d & 0x20)
        y = -y;
    if (d & 0x40) {
        tmp = x;
        x = y;
        y = tmp;
    }
    if (D_2535FAC[c * 2 + 1] & 0x40) {
        m = 0;
        if (d & 0x10)
            m = 0x20;
        if (d & 0x20)
            m |= 0x10;
        d &= 0xffcf;
        d |= m;
    }
    q = &D_2535FAC[c * 2];
    gfx_object_set_flags(b, d ^ q[1]);
    if (q[0] != 0)
        gfx_object_set_image(b, t, 0, (const u8 *)chara_clothes_pics[q[0] - 1]);
    if (room_view == 2 || room_view == 3)
        gfx_object_move_dirty(b, 0x17 - (B->image[0] >> 1), 0x5c - (B->image[1] >> 1));
    else
        gfx_object_move_dirty(b, e + x + (A->image[0] >> 1) - (B->image[0] >> 1),
                     f + y + x + (A->image[1] >> 1) - (B->image[1] >> 1));
    return;
zero:
    gfx_object_set_image(b, 0, 0, 0);
}

/*
 * Draw OUR character (chara_pet_sprite_set = character index; < 100: built-in sprite table
 * chara_sprite_sets, else a downloaded character via dl_chara_pose_pic) in display object id with pose
 * c and flags d, centred at (x, y). When d has no colour mode (bits 0-2), the state forces
 * one: 1 for pet.x062 == 2, 2 for pet.x062 > 2 (sick / dimmed looks?), 4 for pet.x082
 * == 4; 0x800 when pet.x0cc == 1 (dirty?), else 0x400 when pet.x148 is set at life stage
 * 2..3. Objects id+1 and id+2 receive the worn clothes (pet.x06D, chara_draw_clothes) and
 * accessory (x06C, chara_draw_accessory). The siblings chara_draw_second / chara_draw_third / chara_draw_fourth
 * draw the guest / partner characters (sets chara_other_sprite_set, chara_third_sprite_set, chara_fourth_sprite_set with ids
 * chara_other_row, chara_third_row, chara_fourth_row), chara_draw_any any character by id.
 */
void chara_draw_pet(u8 id, u8 b, u8 c, u16 d, s16 x, s16 y)
{
    struct GfxObject *e = &gfx_objects[id];
    u16 v = d;

    if ((save.pet.x062 > 1 || save.pet.x082 == 4) && (d & 7) == 0) {
        if (save.pet.x062 == 2) {
            v &= 0xfff8;
            v |= 1;
        } else if (save.pet.x062 > 2) {
            v &= 0xfff8;
            v |= 2;
        } else if (save.pet.x082 == 4) {
            v &= 0xfff8;
            v |= 4;
        }
    }
    if (save.pet.x0cc == 1)
        v |= 0x800;
    else if (save.pet.x148 && (u8)(save.pet.life_stage - 2) <= 1)
        v |= 0x400;
    if (chara_pet_sprite_set < 100) {
        gfx_object_set_flags(id, v);
        gfx_object_set_image(id, b, 0, (const u8 *)((u32 *)&chara_sprite_sets[chara_pet_sprite_set])[c]);
    } else {
        gfx_object_set_flags(id, v);
        gfx_object_set_image(id, b, 0, (const u8 *)dl_chara_pose_pic(save.pet.chara_row + 0x77, c));
    }
    x -= e->image[0] >> 1;
    y = y - (e->image[1] >> 1) + 0x1c;
    gfx_object_move_dirty(id, x, y);
    if (save.pet.x0cc == 1)
        d |= 0x800;
    chara_draw_clothes(id, id + 1, c, d, x, y, (u8)save.pet.worn_clothes, save.pet.chara_row);
    chara_draw_accessory(id, id + 2, c, d, x, y, (u8)save.pet.worn_accessory, save.pet.chara_row);
}

