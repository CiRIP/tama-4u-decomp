def check(p):
    k = p[0x55]
    perm = PERM[(k & 15) * 8:(k & 15) * 8 + 8]
    val = VAL[(k >> 4) * 8:(k >> 4) * 8 + 8]
    return all(p[0x52 + perm[i]] == val[i] for i in range(8) if i != 3)


def main():
    fw = open(sys.argv[1], 'rb').read()
    pos = 0
    ok = bad = 0
    while True:
        pos = fw.find(b'TAMAGO\0', pos)
        if pos < 0:
            break
        p = fw[pos:pos + 0x100]
        if len(p) == 0x100:
            good = check(p)
            ok += good
            bad += not good
            if not good or '-v' in sys.argv:
                print('%07X %s sig=%s type=%02X cat=%02X id=%s' % (
                    pos + 0x2000000, 'ok ' if good else 'BAD', p[0x52:0x5a].hex(),
                    p[0x4e], p[0x4f], p[0x34:0x44].split(b'\0')[0].decode('ascii', 'backslashreplace')))
        pos += 7
    print('ok=%d bad=%d' % (ok, bad))


main()
